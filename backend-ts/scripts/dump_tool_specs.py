"""Regenerate packages/core/src/tools/specs.ts from the Python tool registry.

Run from repo root while the Python backend still exists:
    OFFERU_DATA_DIR=$(mktemp -d) python3 backend-ts/scripts/dump_tool_specs.py
Keeps tool names, descriptions and input JSON schemas byte-identical to
backend/app/core/tools.py (what /api/tools, MCP and `offeru tool` expose).
"""
import json
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(root / "backend"))
from app.core.tools import TOOLS  # noqa: E402

src = (root / "backend/app/mcp_server.py").read_text(encoding="utf-8")
ns: dict = {}
exec(re.search(r"INSTRUCTIONS = \(.*?\n\)", src, re.S).group(0), ns)
specs = [{"name": t.name, "description": t.description, "inputSchema": t.input.model_json_schema()} for t in TOOLS.values()]
out = root / "packages/core/src/tools/specs.ts"
out.write_text(
    "// GENERATED by backend-ts/scripts/dump_tool_specs.py from backend/app/core/tools.py. Do not edit by hand.\n"
    "// Tool names, descriptions and input schemas exactly as Python exposes them on /api/tools, MCP and `offeru tool`.\n\n"
    "import type { ToolSpec } from \"./schema\";\n\n"
    f"export const MCP_INSTRUCTIONS = {json.dumps(ns['INSTRUCTIONS'], ensure_ascii=False)};\n\n"
    f"export const TOOL_SPECS: ToolSpec[] = {json.dumps(specs, ensure_ascii=False, indent=2)};\n",
    encoding="utf-8",
)
print(f"wrote {out} ({len(specs)} tools)")
